inline const Translation *find(std::string_view text) {
    auto entry = std::lower_bound(std::begin(translations), std::end(translations), text,
        [](const Translation &entry, std::string_view value) { return entry.english < value; });
    return entry != std::end(translations) && entry->english == text ? entry : nullptr;
}

inline const char *tr(const char *text) {
    if (current_language == Language::Chinese && text)
        if (auto entry = find(text))
            return entry->chinese;
    return text;
}

inline const char *label(const char *text) {
    if (text)
        if (auto entry = find(text))
            return current_language == Language::Chinese ? entry->chinese_label : entry->english_label;
    return text;
}

